#!/usr/bin/env python3
"""Protected geul Rust commands; WordCraft required, RHWP checkout optional."""
import importlib.util
import os
from pathlib import Path
import re
import shutil
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("integrity", ROOT / "scripts/external-integrity.py")
integrity = importlib.util.module_from_spec(spec)
spec.loader.exec_module(integrity)


def main():
    args = sys.argv[1:]
    tauri_run = args[:1] == ["run"] and os.environ.get("GEUL_TAURI_RUNNER") == "1"
    application_args = []
    if tauri_run:
        separator = args.index("--") if "--" in args else len(args)
        application_args = args[separator + 1:]
        args = ["build", *args[1:separator]]
    if not args or args[0] not in {"check", "build", "test", "clippy", "fmt", "fetch"}:
        raise RuntimeError("Usage: cargo-geul.py check|build|test|clippy|fmt --check|fetch [Cargo arguments]")
    action = args[0]
    if any(arg.split("=", 1)[0] in {"--manifest-path", "--target-dir", "--config"} for arg in args):
        raise RuntimeError("Use the recorded geul manifest/output configuration")
    cargo = shutil.which("cargo")
    if not cargo:
        raise RuntimeError("cargo must already be installed")
    manifest = ["--manifest-path", str(ROOT / "src-tauri/Cargo.toml")]
    env = {**os.environ, "CARGO_TARGET_DIR": str(ROOT / "src-tauri/target")}
    if "RUST_TOOLCHAIN" in env:
        env["RUSTUP_TOOLCHAIN"] = env["RUST_TOOLCHAIN"]
    command = [cargo, action, *manifest]
    if action == "fetch":
        if len(args) != 1:
            raise RuntimeError("fetch accepts no overrides; only the fixed --locked manifest is used")
        command += ["--locked", "--target", integrity.host_target(env)]
    else:
        if action == "fmt" and "--check" not in args:
            raise RuntimeError("Protected formatting requires --check")
        if action != "fmt":
            command += [flag for flag in ["--locked", "--offline"] if flag not in args]
        command += args[1:]
    writable = [ROOT / p for p in ["target/rhwp-wasm", "src-tauri/target", "src-tauri/gen", "src-tauri/permissions/autogenerated"]]
    integrity.run_readonly([command], writable, ROOT / f"target/rhwp-wasm/geul-{action}-integrity.json",
                           env=env, required=["external/wordcraft"], require_clean=True, prepare_cache=action == "fetch")
    if tauri_run:
        def option(name, default=None):
            for index, value in enumerate(args):
                if value.startswith(name + "="):
                    return value.split("=", 1)[1]
                if value == name:
                    return args[index + 1]
            return default
        profile = option("--profile", "release" if "--release" in args else "debug")
        profile = {"dev": "debug", "test": "debug", "bench": "release"}.get(profile, profile)
        target = option("--target")
        name = tomllib.loads((ROOT / "src-tauri/Cargo.toml").read_text())["package"]["name"]
        binary_name = option("--bin", name)
        if any(value in {".", ".."} or not re.fullmatch(r"[A-Za-z0-9_.-]+", value) for value in [profile, binary_name, *([target] if target else [])]):
            raise RuntimeError("Unsupported Tauri Cargo target/profile/binary path")
        binary = ROOT / "src-tauri/target"
        if target:
            binary /= target
        binary = binary / profile / binary_name
        if binary.is_symlink() or not binary.is_file():
            raise RuntimeError("Tauri application binary was not produced")
        # Cargo compilation was protected. The GUI must retain normal user
        # document access, rather than inherit the build's read-only root.
        os.execvpe(str(binary), [str(binary), *application_args], env)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError) as exc:
        print(str(exc), file=sys.stderr)
        sys.exit(getattr(exc, "returncode", 1))
